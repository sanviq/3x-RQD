import {fileURLToPath} from 'node:url';

import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
test('uploaded photo runs full analysis automatically and maps its snapshot to a real imported segment',async({page,isMobile})=>{
  test.skip(process.env.ROAD_HEALTH_REAL_API!=='1','Requires the actual updated API');
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');await page.getByRole('button',{name:'New inspection',exact:true}).click();
  const response=page.waitForResponse(r=>r.url().endsWith('/api/analyze')&&r.request().method()==='POST');
  await page.locator('input[type=file]').first().setInputFiles({name:'provided-pothole.jpg',mimeType:'image/jpeg',buffer:readFileSync(new URL('../../tests/fixtures/pothole-road.jpg',import.meta.url))});
  const result=await (await response).json();
  expect(result.analysis_region.image_fraction).toBeLessThan(1);
  expect(result.assessment.road_quality_index).toBeNull();
  await expect(page.getByRole('heading',{name:'Road texture & aggregate candidates'})).toBeVisible();
  const chips=page.locator('.measurement').filter({has:page.getByText('Detected chip candidates',{exact:true})});
  await expect(chips.locator('strong')).toHaveText(result.chip_candidate_count.toLocaleString('en-IN'));
  await page.getByRole('button',{name:'Diagnostic overlay',exact:true}).click();
  await expect(page.getByAltText('Processed diagnostic overlay',{exact:false})).toHaveAttribute('src',/^data:image\/png;base64,/);
  if(isMobile)await page.getByRole('button',{name:'Open navigation'}).click();
  await page.getByRole('button',{name:'Road network',exact:true}).click();
  await page.getByLabel('Import road GeoJSON',{exact:true}).setInputFiles(fileURLToPath(new URL('../public/road-network-template.geojson',import.meta.url)));
  await expect(page.getByText('1 connected component',{exact:true})).toBeVisible();
  await page.getByLabel('From network node').selectOption('0');await page.getByLabel('To network node').selectOption('6');
  await expect(page.getByText('2 road segment(s).',{exact:false})).toBeVisible();
  const roadTarget=page.getByRole('button',{name:'Select road Fictional east approach',exact:true});
  await roadTarget.scrollIntoViewIfNeeded();
  const point=await roadTarget.evaluate(el=>{const line=el.parentElement!.querySelector('polyline')!;const a=line.points.getItem(line.points.numberOfItems-2),b=line.points.getItem(line.points.numberOfItems-1);const p=new DOMPoint((a.x+b.x)/2,(a.y+b.y)/2).matrixTransform(line.getScreenCTM()!);return {x:p.x,y:p.y}});
  if(isMobile)await page.touchscreen.tap(point.x,point.y);else await page.mouse.click(point.x,point.y);
  await expect(page.getByLabel('Mapped segment')).toHaveValue('example-east');
  await page.getByRole('button',{name:'Attach current analysis to this segment',exact:true}).click();
  await expect(page.getByRole('heading',{name:'provided-pothole.jpg',exact:true})).toBeVisible();
  const download=page.waitForEvent('download');await page.getByRole('button',{name:'Export segment inspection'}).click();
  expect((await download).suggestedFilename()).toContain('segment-inspection');
  await page.getByRole('button',{name:'Open this capture in digital twin'}).click();
  await page.getByRole('button',{name:'Digital twin',exact:true}).click();
  await expect(page.locator('.road-renderer')).toHaveAttribute('data-renderer','webgl-twin');
  const id=result.defect_detection.defects[0].id;
  await page.getByRole('button',{name:'Inspect '+id+' in original photo',exact:true}).click();
  await expect(page.getByLabel('Twin focus defect')).toHaveValue(id);
  await expect(page.getByAltText('Original uploaded road registration reference')).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
test('network import errors preserve valid road geometry and unknown condition',async({page,isMobile})=>{
  await page.goto('/');if(isMobile)await page.getByRole('button',{name:'Open navigation'}).click();
  await page.getByRole('button',{name:'Road network',exact:true}).click();
  const input=page.getByLabel('Import road GeoJSON',{exact:true});
  const data={type:'FeatureCollection',features:[{type:'Feature',id:'a',properties:{name:'Uninspected road'},geometry:{type:'LineString',coordinates:[[77,13],[77.001,13]]}}]};
  await input.setInputFiles({name:'roads.geojson',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(data))});
  await expect(page.getByText('No capture assigned. Gray roads have unknown condition.',{exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Attach current analysis to this segment',exact:true})).toBeDisabled();
  await input.setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from('{"type":"Point"}')});
  await expect(page.getByRole('alert')).toContainText('WGS84 GeoJSON');
  await expect(page.getByRole('button',{name:'Select road Uninspected road',exact:true})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
