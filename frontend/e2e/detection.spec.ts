import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
test('real pothole photo: API outlines, mapped defects, wheel contact and rejection',async({page,isMobile})=>{
  test.skip(process.env.ROAD_HEALTH_REAL_API!=='1','Requires the updated FastAPI server on port 8000');
  const photo=readFileSync(new URL('../../tests/fixtures/pothole-road.jpg',import.meta.url));
  const failures:string[]=[];page.on('pageerror',e=>failures.push(e.message));
  await page.goto('/');await page.getByRole('button',{name:'New inspection',exact:true}).click();
  const response=page.waitForResponse(r=>r.url().endsWith('/api/detect-defects'));
  await page.locator('input[type=file]').setInputFiles({name:'pothole-road.jpg',mimeType:'image/jpeg',buffer:photo});
  const actual=await (await response).json();
  expect(actual.defects.length).toBeGreaterThan(0);
  expect(actual.defects.some((d:{kind:string;bbox:{x:number;y:number;width:number;height:number}})=>d.kind==='Pothole'&&d.bbox.x<=375&&d.bbox.x+d.bbox.width>=375&&d.bbox.y<=336&&d.bbox.y+d.bbox.height>=336)).toBe(true);
  expect(actual.confidence_calibrated).toBe(false);
  await expect(page.locator('.defect-photo polygon')).toHaveCount(actual.defects.length);
  await page.getByLabel('Show defect outlines',{exact:true}).uncheck();
  await expect(page.getByAltText('Original uploaded road without outlines',{exact:true})).toBeVisible();
  await page.getByLabel('Show defect outlines',{exact:true}).check();
  await page.getByRole('button',{name:'Simulate uploaded road',exact:true}).click();
  await expect(page.locator('.sim-mark-list>button')).toHaveCount(actual.defects.length);
  expect(await page.locator('.sim-mark-list').innerText()).not.toContain('Demo annotation');
  await expect(page.getByRole('button',{name:'Drive again',exact:true})).toBeVisible({timeout:18000});
  const contactRow=page.locator('.drive-results tr').filter({hasText:'Wheel-contacted annotations'});
  const hits=Number((await contactRow.locator('td').nth(1).innerText()).trim());
  expect(hits).toBeGreaterThan(0);
  const peak=page.locator('.drive-results tr').filter({hasText:'Peak body acceleration'});
  expect(parseFloat(await peak.locator('td').nth(1).innerText())).toBeGreaterThan(.01);
  const id=actual.defects[0].id;
  await page.getByLabel('Use '+id+' in simulation',{exact:true}).uncheck();
  await expect(page.locator('.sim-mark-list>button')).toHaveCount(actual.defects.length-1);
  if(isMobile)expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect(failures).toEqual([]);
});
