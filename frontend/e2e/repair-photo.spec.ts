
import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
test('real pothole photo produces original-perspective repairs and horizon-dependent predictions',async({page})=>{
  test.setTimeout(120_000);
  test.skip(process.env.ROAD_HEALTH_REAL_API!=='1','Requires updated FastAPI');
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');await page.getByRole('button',{name:'New inspection',exact:true}).click();
  const detected=page.waitForResponse(r=>r.url().endsWith('/api/detect-defects')&&r.status()===200);
  await page.locator('input[type=file]').first().setInputFiles({name:'provided-pothole.jpg',mimeType:'image/jpeg',buffer:readFileSync(new URL('../../tests/fixtures/pothole-road.jpg',import.meta.url))});
  await detected;await page.getByRole('button',{name:'Simulate uploaded road',exact:true}).click();
  await page.getByRole('button',{name:'Repair & deterioration',exact:true}).click();
  const section=page.getByRole('region',{name:'Photo repair and deterioration simulation'});
  const repaired=section.getByAltText('Same uploaded road with selected potholes filled with asphalt patches');
  await expect(repaired).toBeVisible({timeout:45000});
  const original=await section.getByAltText('Original uploaded road with detected defect outlines').getAttribute('src');
  const fresh=await repaired.getAttribute('src');
  const oldPrediction=await section.getByAltText('Simulated road after 6 months').getAttribute('src');
  expect(original).not.toBe(fresh);expect(oldPrediction).not.toBe(fresh);
  await section.getByRole('button',{name:'12 months',exact:true}).click();
  const future=section.getByAltText('Simulated road after 12 months');
  await expect(future).toBeVisible({timeout:45000});expect(await future.getAttribute('src')).not.toBe(oldPrediction);
  expect(await repaired.getAttribute('src')).toBe(fresh);
  await section.getByLabel('Photo traffic assumption').selectOption('heavy');
  await section.getByLabel('Photo weather assumption').selectOption('wet');
  await expect(future).toBeVisible({timeout:45000});
  await section.getByLabel('Show exact edit masks').check();
  await expect(section.getByAltText('Repair edit mask',{exact:true})).toBeVisible();
  const download=page.waitForEvent('download');await section.getByRole('link',{name:'Download predicted PNG',exact:true}).click();expect((await download).suggestedFilename()).toBe('road-predicted-12-months.png');
  await page.getByRole('button',{name:'Digital twin',exact:true}).click();
  await page.getByRole('button',{name:'Repair & deterioration',exact:true}).click();
  await expect(section.getByLabel('Photo traffic assumption')).toHaveValue('heavy');
  await expect(section.getByLabel('Photo weather assumption')).toHaveValue('wet');
  await expect(section.getByAltText('Simulated road after 12 months')).toBeVisible({timeout:45000});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);expect(errors).toEqual([]);
});
test('photo renderer failure keeps upload and supports retry without duplicate placeholders',async({page})=>{
  test.skip(process.env.ROAD_HEALTH_REAL_API!=='1','Requires updated FastAPI');
  await page.route('**/api/repair-views',route=>route.fulfill({status:503,json:{detail:'Renderer temporarily unavailable'}}));
  await page.goto('/');await page.getByRole('button',{name:'New inspection',exact:true}).click();
  const detected=page.waitForResponse(r=>r.url().endsWith('/api/detect-defects')&&r.status()===200);
  await page.locator('input[type=file]').first().setInputFiles({name:'pothole.jpg',mimeType:'image/jpeg',buffer:readFileSync(new URL('../../tests/fixtures/pothole-road.jpg',import.meta.url))});
  await detected;await page.getByRole('button',{name:'Simulate uploaded road',exact:true}).click();
  await page.getByRole('button',{name:'Repair & deterioration',exact:true}).click();
  const section=page.getByRole('region',{name:'Photo repair and deterioration simulation'});
  await expect(section.getByRole('alert')).toBeVisible();
  expect(await section.locator('img').count()).toBe(0);
  await page.unroute('**/api/repair-views');
  await section.getByRole('button',{name:'Retry photo rendering'}).click();
  await expect(section.getByAltText('Same uploaded road with selected potholes filled with asphalt patches')).toBeVisible({timeout:45000});
});
