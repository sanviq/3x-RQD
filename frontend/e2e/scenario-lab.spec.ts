test.setTimeout(120_000);
test('all lab tools share geometry, matched comparisons and isolated weather',async({page,isMobile})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');if(isMobile)await page.getByRole('button',{name:'Open navigation'}).click();
  await page.getByRole('button',{name:'Scenario lab',exact:true}).click();
  await page.getByRole('button',{name:'Digital twin',exact:true}).click();
  const canvas=page.locator('.road-renderer');await expect(canvas).toHaveAttribute('data-renderer','webgl-twin');
  await page.getByLabel('Twin focus defect').selectOption('D1');
  await page.getByLabel('Twin vertical display gain').focus();await page.getByLabel('Twin vertical display gain').press('End');
  await expect(page.getByRole('img',{name:'Left and right wheel-track road height, in assumed millimetres'})).toBeVisible();
  await page.getByRole('button',{name:'Repair & deterioration',exact:true}).click();
  await page.getByRole('button',{name:'Select all repairs',exact:true}).click();
  await page.getByRole('button',{name:'Compare all three drives',exact:true}).click();
  const rms=page.locator('.drive-results tr').filter({hasText:'Vertical acceleration RMS'});
  await expect(rms.locator('td').nth(1)).not.toHaveText('No recorded drive',{timeout:20000});
  expect(parseFloat(await rms.locator('td').nth(1).innerText())).toBeGreaterThan(0);
  await expect(rms.locator('td').nth(2)).toHaveText('0.00 m/s²');
  expect(parseFloat(await rms.locator('td').nth(3).innerText())).toBeGreaterThan(0);
  const duration=await page.locator('.drive-results tr').filter({hasText:'Elapsed time'}).locator('td').allTextContents();
  expect(duration[1]).toBe(duration[2]);expect(duration[2]).toBe(duration[3]);
  await page.getByLabel('Deterioration months',{exact:true}).focus();await page.getByLabel('Deterioration months',{exact:true}).press('ArrowRight');
  await expect(rms.locator('td').nth(3)).toHaveText('No recorded drive');
  await expect(rms.locator('td').nth(2)).toHaveText('0.00 m/s²');
  await page.getByRole('button',{name:'Repair budget',exact:true}).click();
  const budget=page.getByText('Repair budget ·',{exact:false}).locator('input');await budget.focus();await budget.press('Home');
  await page.getByRole('button',{name:'Recommend affordable repairs',exact:false}).click();
  expect(await page.locator('.sim-viewer tbody input:checked').count()).toBe(0);
  await page.getByRole('button',{name:'Severity heatmap',exact:true}).click();
  await expect(page.getByRole('button',{name:'Defect severity',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Image contrast',exact:true}).click();
  await expect(page.getByAltText('Relative dark contrast of the selected road; not inferred defect severity')).toBeVisible();
  await page.getByRole('button',{name:'Digital twin',exact:true}).click();await page.waitForTimeout(200);
  const before=await canvas.evaluate(c=>(c as HTMLCanvasElement).toDataURL());
  await page.getByRole('button',{name:'Weather lab',exact:true}).click();await page.getByRole('button',{name:'Perspective',exact:true}).click();
  let calls=0;await page.route('**/api/analyze',async route=>{calls++;expect(route.request().postData()).toContain('name="road_quad"');await route.fulfill({json:demoResult})});
  await page.getByRole('button',{name:'Analyze original & altered images'}).click();
  await expect(page.getByText('Simulation analysis complete.',{exact:true})).toBeVisible();expect(calls).toBe(2);
  await page.getByRole('button',{name:'Digital twin',exact:true}).click();await page.waitForTimeout(200);
  expect(await canvas.evaluate(c=>(c as HTMLCanvasElement).toDataURL())).toBe(before);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);expect(errors).toEqual([]);
});
test('detected repair edits survive dimension changes and remain inspectable after repair',async({page})=>{
  test.skip(process.env.ROAD_HEALTH_REAL_API!=='1','Requires updated FastAPI');
  await page.goto('/');await page.getByRole('button',{name:'New inspection',exact:true}).click();
  const reply=page.waitForResponse(r=>r.url().endsWith('/api/detect-defects'));
  await page.locator('input[type=file]').setInputFiles({name:'pothole.jpg',mimeType:'image/jpeg',buffer:readFileSync(new URL('../../tests/fixtures/pothole-road.jpg',import.meta.url))});
  const detection=await (await reply).json();await page.getByRole('button',{name:'Simulate uploaded road',exact:true}).click();
  await expect(page.locator('.sim-mark-list>button')).toHaveCount(detection.defects.length);
  await page.locator('.sim-mark-list>button').first().click();await page.getByLabel('Repair this defect',{exact:false}).check();
  await page.getByLabel('Assumed depth (mm)',{exact:true}).fill('100');
  await page.getByLabel('Assumed road width (m)',{exact:true}).fill('7');
  await expect(page.getByLabel('Repair this defect',{exact:false})).toBeChecked();await expect(page.getByLabel('Assumed depth (mm)',{exact:true})).toHaveValue('100');
  await page.getByRole('button',{name:'Digital twin',exact:true}).click();
  await page.getByLabel('Twin focus defect').selectOption(detection.defects[0].id);
  await page.getByRole('group',{name:'Road scenario'}).getByRole('button',{name:'Repaired',exact:true}).click();
  await expect(page.getByLabel('Twin focus defect')).toHaveValue(detection.defects[0].id);
  await expect(page.locator('.road-renderer')).toHaveAttribute('data-renderer','webgl-twin');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
